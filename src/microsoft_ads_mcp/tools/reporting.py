"""Performance and change-history reports (Reporting v13).

A report is submitted, generated by Microsoft in the background (usually a few
minutes), then downloaded as a zipped CSV from a short-lived link. Rows are
parsed in memory and returned; they are never written to disk or the audit log.
"""

from __future__ import annotations

import asyncio
import re
import time
from typing import Any

from mcp.server.mcpserver import Context

from ..client import MicrosoftAdsClient
from ._common import ids_to_strings
from ._progress import report, run_blocking

SUBMIT = "/Reporting/v13/GenerateReport/Submit"
POLL = "/Reporting/v13/GenerateReport/Poll"
_DATE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
AGGREGATIONS = {
    "Summary",
    "Hourly",
    "Daily",
    "Weekly",
    "WeeklyStartingMonday",
    "Monthly",
    "Yearly",
    "DayOfWeek",
    "HourOfDay",
}
CHANGE_HISTORY_COLUMNS = [
    "DateTime",
    "CampaignName",
    "AdGroupName",
    "ItemChanged",
    "AttributeChanged",
    "HowChanged",
    "OldValue",
    "NewValue",
    "EntityName",
    "EntityId",
    "ChangedBy",
    "Tool",
]

EXAMPLES = """\
Common report types (report_type -> example columns):
  CampaignPerformance -> TimePeriod, CampaignName, CampaignId, Impressions, Clicks, Spend,
    Conversions, Revenue, Ctr, AverageCpc
  AdGroupPerformance, KeywordPerformance (adds Keyword, BidMatchType, QualityScore),
  AdPerformance, SearchQueryPerformance (SearchQuery), AssetGroupPerformance (Performance Max),
  ProductDimensionPerformance / ProductPartitionPerformance (Shopping), GeographicPerformance,
  AudiencePerformance, ShareOfVoice, BudgetSummary, AccountPerformance.
Include TimePeriod when aggregation isn't Summary. Columns and filters differ by report type;
if a request is rejected the error names the problem. Data retention varies by report and
aggregation (see Microsoft's reporting data retention guide)."""


def _date(value: str, name: str) -> dict[str, int]:
    if not _DATE.match(value or ""):
        raise ValueError(f"{name} must be YYYY-MM-DD, got '{value}'.")
    y, m, d = (int(p) for p in value.split("-"))
    return {"Year": y, "Month": m, "Day": d}


def build_report_request(
    client: MicrosoftAdsClient,
    *,
    report_type: str,
    columns: list[str],
    start_date: str | None = None,
    end_date: str | None = None,
    predefined_time: str | None = None,
    aggregation: str | None = "Summary",
    account_ids: list[str] | None = None,
    campaign_ids: list[str] | None = None,
    filters: dict[str, Any] | None = None,
    time_zone: str | None = None,
    name: str | None = None,
    return_only_complete_data: bool = False,
) -> dict[str, Any]:
    rtype = report_type.strip()
    if not rtype or not rtype.replace("_", "").isalnum():
        raise ValueError("report_type must be a report name such as CampaignPerformance.")
    if not rtype.endswith("ReportRequest"):
        rtype += "ReportRequest"
    if not columns:
        raise ValueError("Pass at least one column.")
    time_obj: dict[str, Any] = {}
    if predefined_time:
        if start_date or end_date:
            raise ValueError("Pass either predefined_time or start_date/end_date, not both.")
        time_obj["PredefinedTime"] = predefined_time
    else:
        if not (start_date and end_date):
            raise ValueError("Pass start_date and end_date (YYYY-MM-DD) or predefined_time.")
        time_obj["CustomDateRangeStart"] = _date(start_date, "start_date")
        time_obj["CustomDateRangeEnd"] = _date(end_date, "end_date")
    if time_zone:
        time_obj["ReportTimeZone"] = time_zone
    accounts = ids_to_strings(account_ids) or [client.account(None)]
    scope: dict[str, Any] = {"AccountIds": accounts}
    if campaign_ids:
        scope["Campaigns"] = [
            {"AccountId": accounts[0], "CampaignId": c} for c in ids_to_strings(campaign_ids)
        ]
    req: dict[str, Any] = {
        "Type": rtype,
        "Format": "Csv",
        "FormatVersion": "2.0",
        "ExcludeReportHeader": True,
        "ExcludeReportFooter": True,
        "ExcludeColumnHeaders": False,
        "ReturnOnlyCompleteData": return_only_complete_data,
        "ReportName": name or rtype.removesuffix("ReportRequest"),
        "Columns": list(columns),
        "Scope": scope,
        "Time": time_obj,
    }
    if aggregation:
        if aggregation not in AGGREGATIONS:
            raise ValueError(f"aggregation must be one of {', '.join(sorted(AGGREGATIONS))}.")
        req["Aggregation"] = aggregation
    if filters:
        req["Filter"] = filters
    return {"ReportRequest": req}


def register(mcp, client: MicrosoftAdsClient) -> None:
    def submit(body: dict[str, Any], account_id: str | None) -> str:
        out = client.request("POST", SUBMIT, body=body, account_id=account_id, read_only=True)
        rid = out.get("ReportRequestId") if isinstance(out, dict) else None
        if not rid:
            raise RuntimeError(f"No ReportRequestId in the response: {out}")
        return str(rid)

    def poll(report_request_id: str, account_id: str | None) -> dict[str, Any]:
        out = client.request(
            "POST",
            POLL,
            body={"ReportRequestId": report_request_id},
            account_id=account_id,
            read_only=True,
        )
        return (out or {}).get("ReportRequestStatus") or {}

    def rows_payload(report_request_id: str, url: str | None, max_rows: int) -> dict[str, Any]:
        if not url:
            return {
                "report_request_id": report_request_id,
                "status": "Success",
                "row_count": 0,
                "rows": [],
                "message": "The report has no data for these settings.",
            }
        rows = client.parse_csv_file(client.download(url))
        return {
            "report_request_id": report_request_id,
            "status": "Success",
            "row_count": len(rows),
            "rows": rows[: max(0, max_rows)],
            "truncated": len(rows) > max_rows,
        }

    async def run(body, account_id, max_rows, timeout_seconds, poll_seconds, ctx):
        rid = await run_blocking(submit, body, account_id)
        step = 1
        await report(ctx, step, None, f"Submitted report {rid}")
        deadline = time.monotonic() + timeout_seconds
        while True:
            status = await run_blocking(poll, rid, account_id)
            state = status.get("Status")
            step += 1
            if state == "Success":
                await report(ctx, step, None, "Report ready; downloading")
                payload = await run_blocking(
                    rows_payload, rid, status.get("ReportDownloadUrl"), max_rows
                )
                await report(ctx, step + 1, None, f"Downloaded {payload['row_count']} rows")
                return payload
            if state not in ("Pending", None):
                return {"report_request_id": rid, "status": state, "message": "The report failed."}
            if time.monotonic() >= deadline:
                return {
                    "report_request_id": rid,
                    "status": state,
                    "message": "Still generating. Check later with microsoft_ads_poll_report.",
                }
            await report(ctx, step, None, f"Report {state}; waiting")
            await asyncio.sleep(max(0.0, poll_seconds))

    @mcp.tool(
        description=(
            "Submit a report request. It is generated in the background: check it with "
            "microsoft_ads_poll_report, then call microsoft_ads_download_report (or use "
            "microsoft_ads_run_report to do all three).\n\nDates are YYYY-MM-DD, or pass "
            "predefined_time (e.g. LastSevenDays, LastMonth, ThisMonth). aggregation: Summary "
            "(default), Daily, Weekly, Monthly and others. filters is the report's Filter "
            'object, e.g. {"DeviceType": "Computer"}. account_ids defaults to the configured '
            "account; campaign_ids narrows the scope.\n\n" + EXAMPLES
        )
    )
    def microsoft_ads_submit_report(
        report_type: str,
        columns: list[str],
        start_date: str | None = None,
        end_date: str | None = None,
        predefined_time: str | None = None,
        aggregation: str = "Summary",
        account_ids: list[str] | None = None,
        campaign_ids: list[str] | None = None,
        filters: dict[str, Any] | None = None,
        time_zone: str | None = None,
        name: str | None = None,
        account_id: str | None = None,
    ) -> dict[str, Any]:
        body = build_report_request(
            client,
            report_type=report_type,
            columns=columns,
            start_date=start_date,
            end_date=end_date,
            predefined_time=predefined_time,
            aggregation=aggregation,
            account_ids=account_ids or ([account_id] if account_id else None),
            campaign_ids=campaign_ids,
            filters=filters,
            time_zone=time_zone,
            name=name,
        )
        return {"report_request_id": submit(body, account_id), "status": "Pending"}

    @mcp.tool()
    def microsoft_ads_poll_report(
        report_request_id: str, account_id: str | None = None
    ) -> dict[str, Any]:
        """Check a report's status: Pending, Success or Error.

        When Success, call microsoft_ads_download_report to get the rows. Report
        request IDs expire after a day or two.
        """
        status = poll(report_request_id, account_id)
        return {
            "report_request_id": report_request_id,
            "status": status.get("Status"),
            "has_data": bool(status.get("ReportDownloadUrl")),
        }

    @mcp.tool()
    def microsoft_ads_download_report(
        report_request_id: str, max_rows: int = 1000, account_id: str | None = None
    ) -> dict[str, Any]:
        """Download a finished report and return its rows (up to max_rows).

        Rows are held in memory only. row_count is the full count; truncated says
        whether rows were cut to max_rows. Files over MICROSOFT_ADS_MAX_DOWNLOAD_MB
        are refused.
        """
        status = poll(report_request_id, account_id)
        if status.get("Status") != "Success":
            return {
                "report_request_id": report_request_id,
                "status": status.get("Status"),
                "message": "Report isn't ready; check again with microsoft_ads_poll_report.",
            }
        return rows_payload(report_request_id, status.get("ReportDownloadUrl"), max_rows)

    @mcp.tool(
        description=(
            "Submit a report, wait for it with progress updates, and return its rows. Same "
            "arguments as microsoft_ads_submit_report, plus max_rows (default 1000), "
            "timeout_seconds (default 900) and poll_seconds (default 15). If it times out, "
            "the report_request_id is returned so you can check later.\n\n" + EXAMPLES
        )
    )
    async def microsoft_ads_run_report(
        report_type: str,
        columns: list[str],
        start_date: str | None = None,
        end_date: str | None = None,
        predefined_time: str | None = None,
        aggregation: str = "Summary",
        account_ids: list[str] | None = None,
        campaign_ids: list[str] | None = None,
        filters: dict[str, Any] | None = None,
        time_zone: str | None = None,
        name: str | None = None,
        max_rows: int = 1000,
        timeout_seconds: float = 900,
        poll_seconds: float = 15,
        account_id: str | None = None,
        ctx: Context | None = None,
    ) -> dict[str, Any]:
        body = build_report_request(
            client,
            report_type=report_type,
            columns=columns,
            start_date=start_date,
            end_date=end_date,
            predefined_time=predefined_time,
            aggregation=aggregation,
            account_ids=account_ids or ([account_id] if account_id else None),
            campaign_ids=campaign_ids,
            filters=filters,
            time_zone=time_zone,
            name=name,
        )
        return await run(body, account_id, max_rows, timeout_seconds, poll_seconds, ctx)

    @mcp.tool()
    async def microsoft_ads_change_history(
        start_date: str | None = None,
        end_date: str | None = None,
        predefined_time: str | None = None,
        columns: list[str] | None = None,
        campaign_ids: list[str] | None = None,
        filters: dict[str, Any] | None = None,
        max_rows: int = 1000,
        timeout_seconds: float = 900,
        account_id: str | None = None,
        ctx: Context | None = None,
    ) -> dict[str, Any]:
        """Who changed what, and when, in one account: runs the change history report.

        Rows include the item and attribute changed, old and new values, who changed
        it and with which tool. Pass start_date/end_date (YYYY-MM-DD) or
        predefined_time (LastSevenDays, LastMonth or LastThreeMonths). filters, e.g.
        {"ItemChanged": "Campaign", "HowChanged": "Changed"}. Changes take about an
        hour to appear.
        """
        if not (start_date or predefined_time):
            predefined_time = "LastSevenDays"
        body = build_report_request(
            client,
            report_type="SearchCampaignChangeHistory",
            columns=columns or CHANGE_HISTORY_COLUMNS,
            start_date=start_date,
            end_date=end_date,
            predefined_time=predefined_time,
            aggregation=None,
            account_ids=[account_id] if account_id else None,
            campaign_ids=campaign_ids,
            filters=filters,
        )
        return await run(body, account_id, max_rows, timeout_seconds, 15, ctx)
